def severity(expected: str, uid: str) -> str:
    e = (expected or "").lower()
    if any(k in e for k in ("nullreference", "nre", "exception propagate", "partial commit", "không lock", "race", "concurrency")):
        return "Critical"
    if "⚠" in (expected or "") or any(k in e for k in ("settle", "rollback", "forbidden", "notfound", "duplicate", "validation", "fuelcost", "canimport")):
        return "Major"
    return "Minor"


def root_cause(expected: str) -> str:
    text = re.sub(r"\s+", " ", (expected or "").strip())
    # Prefer warning clause as root cause when present
    if "⚠" in text:
        part = text.split("⚠", 1)[1].strip()
        return part[:180]
    return text[:180]


